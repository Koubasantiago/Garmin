import assert from 'node:assert/strict';
import {cadenceSpm,runCadence,zoneIndex,zoneBoundaries,zoneSeconds,migrateCadenceRun} from '../src/analysis.js';
const opts={maxHr:200,thresholds:[60,70,80,90]};
assert.deepEqual(zoneBoundaries(opts),[120,140,160,180]);
assert.equal(zoneIndex(110,opts),0);
assert.equal(zoneIndex(120,opts),1);
assert.equal(zoneIndex(140,opts),2);
assert.equal(zoneIndex(160,opts),3);
assert.equal(zoneIndex(180,opts),4);
assert.equal(zoneIndex(null,opts),-1);
assert.equal(zoneIndex(250,opts),-1);
assert.equal(cadenceSpm(82.5),165);
assert.equal(cadenceSpm(174),174);
assert.equal(cadenceSpm(0),null);
assert.equal(runCadence({cadence:168}),168);
assert.equal(runCadence({cadence:null,points:[{cadence:170},{cadence:172}]}),171);
const p=[{t:0,hr:110},{t:10,hr:125},{t:20,hr:145},{t:30,hr:165},{t:40,hr:185},{t:50,hr:null},{t:55,hr:170},{t:180,hr:170},{t:190,hr:220}];
assert.deepEqual(zoneSeconds(p,opts),{seconds:[10,10,10,20,10],valid:60});
const legacy={source:'FIT',cadence:85,points:[{cadence:87}],id:'test'};
const migrated=migrateCadenceRun(legacy);
assert.equal(migrated.cadence,170);
assert.equal(migrated.points[0].cadence,174);
assert.deepEqual(migrateCadenceRun(migrated),migrated);
assert.equal(migrateCadenceRun({cadence:170,points:[]}).cadence,170);
console.log('Analytics: 19 kontrol prošlo.');
